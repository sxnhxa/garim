"""v0·기준선용 주소 정규식. v1은 NER이 주소를 맡는다(명세 0절 표: ADDRESS = NER, v0·기준선은 도로명 정규식).

정답 범위(명세 7절): 시·도부터 번지까지, 동·호수·층 포함. "성북구에 사는"처럼 지역 이름만 있으면 정답이 아니다.
그래서 도로명+건물번호나 지번(동·가·리·마을·읍·면+번지)이 있어야 주소로 보고, 앞의 시·도·시군구와 뒤의 동·호·층·괄호·건물명을 붙인다.
채점은 정답을 덮으면 맞음(넓어도 맞음)이라 경계는 넓은 쪽으로 잡는다.
한계: 시·군·구로 끝나는 앞 단어(이름 "강재구", 붙여 쓴 "주소는서울시")는 구간에 같이 들어간다.
      도로명만 있는 주소("테헤란로 123")는 받지만, 그 꼴과 같은 "가는길 10"은 주소로 잡힌다(단위가 붙으면 안 잡음).
      "서울시 강남구 역삼동 테헤란로 123"처럼 도로명 앞에 동이 오면 "테헤란로 123"부터 잡는다.
      아파트·동호수만 있는 문장("래미안 101동 1203호")은 시·도~번지가 없어 주소로 안 본다.
"""
import re

from app.regex_detect import _NORMALIZE

SIDO = (r"(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주)"
        r"(?:특별자치시|특별자치도|특별시|광역시|시|도)?|(?:충청|전라|경상)[남북]도")
# 단위 하나는 원자 그룹(Python 3.11+)으로 한 번 정하면 되돌아가지 않는다. 붙여 쓴 "시시시…"에서 나누는 경우의 수가 폭발하는 걸 막는다.
# 띄어 쓴 단위("양구군 ")는 공백 앞까지 통째로, 붙여 쓴 단위("서울시강남구")는 처음 나오는 시·군·구·읍·면에서 끊는다.
# "~면"은 동사 어미("하시면·그러면·해보면")가 아닐 때만 읍·면으로 본다
# 실제 면 이름 중 어미와 끝 글자가 같은 것(남하면·진보면 등)은 따로 받는다. "가평 하면"은 "그렇게 하면"과 같아 뺐다
_UNIT_END = r"(?:시|군|구|읍|(?<![시으하러되라다보])면|(?<=남하|서하|북하|상하|진보|우보|석보)면)"
UNIT = rf"(?:(?>[가-힣]{{1,6}}{_UNIT_END}(?=[ \r\n]))|(?>[가-힣]{{1,6}}?{_UNIT_END}))"
GAP = r"(?:,? {1,2}|\r?\n)?"  # 단위 사이: 붙여 씀·공백 1~2칸·쉼표·줄바꿈(윈도우 \r\n 포함 — 메모장 .txt)
PREFIX = rf"(?:(?:{SIDO}|{UNIT}){GAP}){{1,4}}"
PART_RE = re.compile(rf"{SIDO}|{UNIT}")
# 번호 뒤에 오면 주소가 아니다(개수·시간·돈·순서·범위). 번지·동호·층은 주소 꼬리라 뺀다.
# "을지로 2가"·"구로 3동"처럼 한 자리 숫자에 바로 붙은 가·동은 지역 이름이라 주소가 아니다.
# 건물번호 뒤 조사는 주소다: "123도 배송되나요"(도는 뺌), "124가 맞나요"(두 자리 이상·하이픈 번지 뒤 가), "123부터", "123인데요"
_U = (r"(?:개|명|곳|번(?!지)|분|초|시|원|만|천|억|년|월|일|주|살|세|회|차|건|권|장|등|인(?!데|가요)|위|대|박|가지|점|편|부(?!터|근)"
      r"|배|할|(?<!\d\d|-\d)가(?:역|(?![가-힣]))|동(?![가-힣])|퍼센트|%|[~∼]|cm|km|㎞|kg|m(?![A-Za-z]))")
NOT_ADDRESS_AFTER = rf"(?!{_U}| {_U}(?![가-힣]))"  # 띄어 쓴 단위는 그 단어가 거기서 끝날 때만("123 대림아파트"는 주소)
# 건물번호·번지: 하이픈 하나까지. 뒤에 숫자·소수점·하이픈숫자·천 단위 쉼표가 이어지면 다른 번호(전화·계좌·금액)의 일부다.
# 문장 끝 마침표("…123.")와 CSV 쉼표("…123,010-…")는 받는다
NUMBER = rf"(?:지하 ?)?\d{{1,5}}(?:-\d{{1,5}})?(?!\d|\.\d|-\d|,\d{{3}}(?![\d-])){NOT_ADDRESS_AFTER}"
TAIL = (r"(?:,? ?(?:지하 ?|[Bb])?(?:\d{1,4}|[A-Za-z가나다라마바사아자차카타파하])(?:동|호(?!선)|층)"  # "3층에서"도 받는다. "2호선"은 뺀다
        r"|,? ?\([가-힣A-Za-z0-9 ,.·-]{1,30}\)"  # 괄호 안 전화번호까지 먹어도 detect_address가 번호 앞에서 자른다
        r"|,? ?[가-힣A-Za-z0-9]{1,15}(?= ?(?:\d{1,4}|[A-Za-z가나다라마바])동)"  # 단지명("래미안") + N동
        r"|,? ?[가-힣A-Za-z0-9]{1,15} ?(?:아파트|빌라|빌딩|타워|오피스텔|맨션|하이츠|캐슬|연립|타운|상가|센터|프라자|플라자|팰리스|마을))")
# 시작 위치에서 60자 안에 숫자가 없으면 바로 포기한다(숫자 없는 긴 글을 빨리 넘기는 거름망)
NEAR_DIGIT = r"(?=\D{0,60}\d)"
# 도로명: "테헤란로", "테헤란로7길", "테헤란로 7길", "중앙로12번길", Faker 꼴 "선릉074길"·"서초대90가"·"역삼거리"
ROAD = (rf"{NEAR_DIGIT}(?P<pre>{PREFIX})?(?P<road>[가-힣]{{1,10}}(?:\d{{1,3}}번?| \d{{1,3}}번?(?=길))?(?P<suf>로|길|거리|가))"
        rf"(?: {{1,2}}|\r?\n)?(?P<num>{NUMBER})(?:{TAIL}){{0,4}}")
# 지번: 앞에 시·도나 시·군·구가 하나 이상 꼭 있어야 한다("101동 1203호"·"역삼동 3명"을 막으려고)
LAND = (rf"{NEAR_DIGIT}(?P<pre>{PREFIX})(?P<road>[가-힣][가-힣0-9]{{0,7}}(?:동|가|리|마을|읍|면)|[가-힣]{{1,6}} \d{{1,2}}가) ?(?:산 ?)?"
        rf"(?P<num>{NUMBER})(?:번지)?(?:{TAIL}){{0,4}}")
ROAD_RE, LAND_RE = re.compile(ROAD), re.compile(LAND)

# 조사 "로/으로"로 끝나는 흔한 말("전화로 1588-…")과 부사 한 단어("바로 3층", "주로 2명")는 도로명이 아니다. 앞부분이 있어도 거른다.
# 부사는 단어 전체가 같을 때만 본다("언주로"·"새말로"는 실제 도로명 꼴)
COMMON_RO = re.compile(r"(?:으|전화|문자|메일|택배|카드|현금|계좌|통장|번호|우편|팩스|카톡|앱|직접|별도|따로|대신|이쪽|그쪽|저쪽"
                       r"|여기|거기|저기|므)로$|^(?:스스|별|주|바|새|서|위|고|가|세|억지|최초|상대|차례)로$")


def _ok(m):
    if "suf" not in m.re.groupindex:  # 지번은 앞부분(시·도·시군구)이 늘 있다
        return True
    num = m.group("num").removeprefix("지하").strip()
    # Faker 꼴 "…가·…거리"는 앞 단위가 둘 이상일 때만(일상어 "누가 3", "서울 거리 3"을 막으려고)
    return ((m.group("suf") in ("로", "길") or len(PART_RE.findall(m.group("pre") or "")) >= 2)
            and not COMMON_RO.search(m.group("road"))
            and not num.startswith("0")  # "번호로 010…"·"다시 번호로 0505…"(Faker 도로명 건물번호는 0으로 시작하지 않는다)
            and not re.fullmatch(r"1[5-9]\d\d-\d{4}", num))  # 대표번호 "전화로 1588-0000"


DETAIL_RE = re.compile(r"(?:\d{1,4}|[A-Za-z가나다라마바])(?:동|호|층)")


def detect_address(text: str, taken: list[dict]) -> list[dict]:
    """주소 구간. 이미 잡힌 번호(taken)와 겹치면 번호 구간만 빼고 나머지를 주소로 남긴다(명세 마스킹 규칙 1의 취지: 버리면 노출된다).
    번호 앞 조각은 괄호 꼬리 안에서 잘렸으면 그 괄호 앞까지("…123 (연락처 010-…)" → "…123"),
    번호 뒤 조각은 동·호·층이 있을 때만 남긴다("…123 (010-…) 101동 202호"의 "101동 202호").
    번호가 주소 시작 자리부터 겹치면 그 후보는 버린다(번호 정규식끼리는 지금 이 경우가 없다. 기준선에서 NER 이름을 taken에 넣을 때 다시 본다)."""
    norm = text.translate(_NORMALIZE)
    spans = sorted((m.start(), m.end()) for r in (ROAD_RE, LAND_RE) for m in r.finditer(norm) if _ok(m))
    merged = []
    for s, e in spans:  # 도로명·지번 후보가 겹치면 하나로
        if merged and s < merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], e)
        else:
            merged.append([s, e])
    out = []
    for s, e in merged:
        hit = sorted((t["start"], t["end"]) for t in taken if s < t["end"] and t["start"] < e)
        if not hit:
            out.append({"type": "ADDRESS", "start": s, "end": e, "source": "regex"})
            continue
        if hit[0][0] <= s:
            continue
        pieces, pos = [], s
        for hs, he in hit:
            pieces.append((pos, hs))
            pos = max(pos, he)
        pieces.append((pos, e))
        for i, (ps, pe) in enumerate(pieces):
            if i == 0:
                paren = norm.rfind("(", ps, pe)
                if paren > norm.rfind(")", ps, pe) and not DETAIL_RE.search(norm, paren, pe):  # "(101동 202호, 010-…)"는 동호까지 남긴다
                    pe = paren
            elif i > 0 and not DETAIL_RE.search(norm, ps, pe):
                continue
            while ps < pe and norm[ps] in " ),\r\n":  # 앞쪽은 닫는 괄호를, 뒤쪽은 여는 괄호를 깎는다("(역삼동)"의 ")"는 남긴다)
                ps += 1
            while pe > ps and norm[pe - 1] in " (,\r\n":
                pe -= 1
            if ps < pe:
                out.append({"type": "ADDRESS", "start": ps, "end": pe, "source": "regex"})
    return out
