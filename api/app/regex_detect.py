"""정규식으로 번호류 개인정보 위치를 찾는다. 반환 형식은 docs/api-spec.md의 entities와 같다."""
import re

# 전각 숫자·여러 대시·특수 공백을 ASCII로 1:1 바꾼다. 글자 수가 그대로라 위치는 원문 기준 그대로다
# (NFKC는 ㈜ -> (주)처럼 길이가 바뀌어서 쓰지 않는다)
_NORMALIZE = str.maketrans(
    "０１２３４５６７８９－‐‑‒–—−＋（）＠． 　",
    "0123456789-------+()@.  ",
)

# 번호 사이 구분자: 하이픈·점(양옆 공백 1칸까지), 공백 1칸, 없음 + 줄바꿈(윈도우 \r\n 포함)
# 탭·두 칸 공백은 안 받는다. 엑셀에서 복사한 표의 숫자 칸들이 번호로 이어 붙기 때문
# 한계: "100000 - 1500000원" 같은 쉼표 없는 금액 범위, 한 줄에 숫자 하나씩 쓴 목록은 번호로 잡힐 수 있다
SEP = r"(?: ?[-.] ?| ?)\r?\n?"

# 주민등록번호·외국인등록번호: 생년월일 6자리 + 구분자 + 뒷자리 첫 숫자 + 6자리
# 뒷자리 첫 숫자: 1·2 = 1900년대생, 3·4 = 2000년대생, 5~8 = 외국인
# 월 00~12, 일 00~31: Faker ko_KR ssn()이 00월·00일을 만들어서 00도 받는다
# 한계: 체크섬은 안 본다(재현율 우선). 날짜처럼 생긴 13자리 주문번호·바코드(880...)·법인등록번호도 잡힌다
RRN = re.compile(rf"(?<!\d)\d{{2}}(?:0\d|1[0-2])(?:[0-2]\d|3[01]){SEP}[1-8]\d{{6}}(?!\d)")

# 전화번호
# 시작: +82 / +82 (0) / +82-0 / (02) / 0
#   여는 괄호는 뒤에 "0 + 숫자 1~3개 + 닫는 괄호"가 있을 때만 구간에 넣는다(\((?=0\d{1,3}\))).
#   그래서 "(02)123-4567"은 괄호까지 잡고, "김민수(010-1234-5678)"은 괄호를 빼고 010부터 잡는다
# 앞자리: 휴대폰 식별번호 10·11·16~19, 서울 2, 지역 x1~x5, 인터넷전화 70, 안심번호 502~508
#   실제 지역번호는 31~33·41~44·51~55·61~64뿐인데 재현율 때문에 끝자리 1~5로 넓게 받는다
# 끝: 바로 뒤에 숫자가 더 붙으면 전화로 안 본다
#   "010-1234-5678-12"처럼 "-숫자"가 이어지면 하이픈 번호 전체가 계좌 후보가 되고(_shape는 이걸 전화 모양으로 안 본다),
#   주변에 계좌 단어가 있으면 계좌가 통째로 가져간다. 없으면 전화 부분이라도 가린다(재현율 우선)
# 한계: "연락처 02 010-1234-5678"처럼 앞에 지역번호 모양 숫자가 붙으면 "02 010-1234"로 묶여 뒤 4자리가 남는다
PHONE = re.compile(
    rf"(?<![\d+])(?:\+82{SEP}(?:\(0\){SEP}|0)?|\((?=0\d{{1,3}}\))0|0)"
    rf"(?:1[016789]|2|[3-6][1-5]|70|50[2-8])(?:\){SEP}|{SEP})"
    rf"\d{{3,4}}{SEP}\d{{4}}(?!\d)"
)

# 이메일: 한글도 \w에 걸려서 영문·숫자를 직접 적는다. 첫 글자는 영문·숫자, 끝은 영문 2자 이상(.com, .kr)
EMAIL = re.compile(
    r"(?<![A-Za-z0-9])[A-Za-z0-9][A-Za-z0-9._%+-]*@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}"
)

# 계좌번호 후보: 숫자 10자리 이상(국내 은행 계좌 자릿수: 신한 12, 우리·농협 13, 국민·하나 14 등)
# 세 모양을 이 순서로 본다(섞진 않는다). 붙여 쓴 것·공백형은 14자리까지, 하이픈형은 상한 없음
#   하이픈형: 하이픈으로 이어진 번호 한 줄 전체(숫자 10개 이상, 상한 없음). 중간에서 자르거나 중간부터 시작하지 않는다.
#     자르면 뒤 토막이("1234-5678-9012-3456"의 3456), 중간부터 시작하면 앞 토막이("2024-1124-…"의 2024) 노출되고
#     앞 토막에 붙은 라벨(주문번호 등)도 못 본다. 은행코드가 붙은 "088-110-123-456789"도 통째로 가린다
#   붙여 쓴 것: 10~14자리. 15자리 이상("123456789012345")은 계좌로 안 본다.
#     공백형보다 먼저 봐서 "110123456789 12월"의 " 12"를 계좌에 붙이지 않는다
#   공백형: 숫자 사이 공백 1칸. 뒤에 "-숫자 3개"가 오면 끊지 않는다("입금일 20261124 010-1234-5678"의 날짜+전화 앞부분을 묶지 않으려고).
#     날짜 끝("2024.11.24 110 123 456789"의 24)부터 묶일 수 있다. 묶인 게 전화·주민번호면 _shape가 돌려보낸다
# 한계: 공백으로 끊은 계좌 뒤에 숫자가 오면("110 123 456789 12월") 14자리까지 이어 붙인다.
#       앞 숫자와 합쳐 토막 경계에서 10~14자리가 되면 공백형이 거기서 끊어 뒤 토막이 남는다
#       ("송금 25000 110 123 456789", "송금 12 123456 01 123456", 15자리 이상을 공백으로 끊은 "1234 5678 9012 3456").
#       하이픈 계좌 앞에 숫자가 띄어 붙어도 그렇다("입금 50000 726183-87-315494"는 공백형이 "50000 726183"을 먼저 가져간다).
#       주민번호·전화와 달리 " - "나 "."로 끊은 계좌("110 - 123 - 456789", "110.123.456789")는 못 잡는다
ACCOUNT = re.compile(
    r"(?<!\d)(?:(?=(?:\d-?){10})\d+(?:-\d+)+(?!\d)|\d{10,14}(?!\d)|\d(?: ?\d){9,13}(?!\d)(?!-\d{3}))"
)

# 계좌 쪽 단어. "은행"이 국민은행·우리은행, "뱅크"가 카카오뱅크·토스뱅크, "예금"이 예금주를 덮는다
# 보상금·지급·환불·받으실: 계좌·은행 말 없이 돈을 보낸다는 맥락만 있는 문장("보상금은 110-...로 보내 드립니다").
#   이 넷은 다른 번호 옆에도 자주 와서("환불 접수번호 …", "보험금 지급 증권번호 …") 그 라벨들을 NUMBER_LABEL에 넣었다
# "우체국택배"의 우체국은 택배 회사라 안 친다("우체국 택배비"는 친다)
ACCOUNT_WORDS = re.compile(
    r"계좌|통장|예금|입금|출금|송금|이체|보상금|지급|환불|받으실"
    r"|은행|뱅크|카뱅|케뱅|농협|신한|새마을|우체국(?! ?택배(?!비))|수협|신협|씨티|SC제일"
    r"|(?<![A-Za-z])(?i:kb|nh|ibk)(?![A-Za-z])"
)
# 평소에도 쓰는 은행 줄임말은 따로 떨어진 단어로 번호 바로 옆에 붙을 때만 친다. 뒤에 붙을 땐 조사("국민으로", "우리예요")까지 받는다
# ("김하나", "하나로마트", "대한산업"처럼 한글 단어의 일부면 안 친다. 부산·제주 같은 지역명은 주소 첫 단어와 겹쳐서 뺐다.
#  부산은행처럼 쓰면 "은행"이 잡는다)
# 한계: "900101-1234567 우리 집"처럼 번호 바로 뒤에 따로 쓰면 계좌로 본다
BANK_SHORT = "국민|우리|하나|기업|산업|카카오|토스"
BANK_SHORT_BEFORE = re.compile(rf"(?<![가-힣])(?:{BANK_SHORT})(?![가-힣])[ :()]*$")
BANK_SHORT_AFTER = re.compile(rf"^[ (]*(?:{BANK_SHORT})(?:으로|로|이고|이에요|예요|에요|이요|입니다|이며)?요?(?![가-힣])")
# 다른 번호의 라벨(이 번호는 계좌가 아니다). 번호 바로 앞(조사·콜론·괄호까지)이나 바로 뒤에 붙어 있을 때만 친다.
# 떨어져 있으면 문맥일 뿐이라 안 본다("휴대폰으로 연락 주시고 110-...로 입금", "주문 건 환불은 110-...")
# 라벨 뒤에는 조사·공백·콜론만 올 수 있어서 "택배비"·"주문하신"은 라벨이 아니다.
# 주문·사업자·카드·접수 등은 "번호"까지 있어야 라벨이다("계좌(사업자) 110-..."는 계좌)
# "문의·연락·문자"는 "계좌 문의 110-..." 같은 진짜 계좌를 막아서 넣지 않는다
NUMBER_LABEL = (
    r"(?:주문 ?|사업자 ?(?:등록 ?)?|(?:카드|접수|처리|관리|증권|사건|청구|회원|고객|거래) ?)번호|(?:송장|택배)(?: ?번호)?"
)
LABEL_BEFORE = re.compile(rf"(?:{NUMBER_LABEL})(?:은|는|이|가)?[ :()\r\n]*\Z")
# 주민번호 모양 번호에는 주민번호 라벨도 친다. 뒤에 은행 이름이 와도 라벨이 이긴다("주민번호 900101-... 국민은행 고객")
RRN_LABEL_BEFORE = re.compile(
    rf"(?:(?:주민|외국인)(?: ?(?:등록 ?)?번호)?|생년월일|실명(?: ?번호)?|{NUMBER_LABEL})(?:은|는|이|가)?[ :()\r\n]*\Z"
)
LABEL_AFTER = re.compile(rf"^[ (]*(?:{NUMBER_LABEL})(?:은|는|이|가)?(?![가-힣])")
# 전화 모양 숫자는 바로 앞에 "계좌"·"통장"이 붙어 있을 때만 계좌(평생계좌 "입금 계좌 010-1234-5678").
# 라벨과 번호 사이 줄바꿈(\n, \r\n)도 받는다
SHAPED_ACCOUNT_LABEL = re.compile(r"(?:계좌|통장)(?: ?번호)?[ :\r\n]*\Z")
# 주민번호 모양(날짜 같은 계좌 "입금 계좌 1002123456789")은 라벨 뒤 조사·괄호·하이픈도 받는다
# ("계좌는 1002123456789", "계좌번호를 …", "계좌(우리) …"). 우리은행 1002…를 붙여 쓰면 넷 중 하나꼴로 주민번호 모양이라 흔하다
RRN_SHAPED_ACCOUNT_LABEL = re.compile(r"(?:계좌|통장)(?: ?번호)?(?:은|는|이|가|을|를|로|으로)?[ :(\r\n-]*\Z")
# 번호 바로 뒤에 계좌·통장이 붙어도 계좌("보상금은 1002123456789 계좌로").
# 단 그 뒤에 다른 번호가 이어지면 다음 번호의 라벨이라 안 친다("홍길동 900101-1234567 계좌 110-...", "계좌: 신한 110-...")
RRN_SHAPED_ACCOUNT_AFTER = re.compile(r"^[ ()]*(?:계좌|통장)(?!(?: ?번호)?[ :]*(?:[가-힣]+ )?\d)")
# 주민번호 모양은 은행 이름이 바로 앞뒤에 붙어 있어도 계좌("8612307785589 (국민)", "신한은행 1002123456789").
# 전화 모양에는 안 쓴다. "토스 010-1234-5678"처럼 전화번호로 송금하는 말과 헷갈린다
BANK_NAMES = (
    r"은행|뱅크|카뱅|케뱅|농협|신한|새마을|우체국(?! ?택배(?!비))|수협|신협|씨티|SC제일|(?<![A-Za-z])(?i:kb|nh|ibk)(?![A-Za-z])"
)
BANK_BEFORE = re.compile(rf"(?:{BANK_NAMES})[ :()\r\n]*\Z")
BANK_AFTER = re.compile(rf"^[ (]*[가-힣]*(?:{BANK_NAMES})")
# 앞뒤 창을 자를 때 쓰는 "다른 번호": 숫자 9개 이상(구분자 포함, 전화·주민번호·계좌 길이). 이웃 번호의 라벨을 끌어오지 않으려고.
# 금액·날짜("25000원", "2026.11.30")에선 안 자른다. 자르면 그 앞의 '송금'·'이체'를 못 본다
# 한계: 8자리 이하 이웃 번호의 라벨은 끌어올 수 있다
OTHER_NUMBER = re.compile(r"\d(?:[ .-]?\d){8,}")


def _shape(norm, m):
    """후보의 시작 위치가 전화·주민번호 매치 안에 있으면 그 종류.
    정확히 같거나, 그걸로 시작하거나("010 1234 5678 3"), 그 뒤쪽이거나("+82.10-1234-5678"의 10-…)인 경우다.
    날짜 끝 같은 1~2자리 토막 뒤에 붙은 매치도 친다("11/24 01012345678"의 "24 010…").
    숫자 토막 뒤 매치가 후보 끝을 넘어가도 친다("환불 25000 010 1234 5678"의 후보 "25000 010 1234").
    그 밖에 후보 중간에서 시작하는 매치는 안 본다(카카오뱅크 "3333-02-1234567"의 "02-1234567"은 서울 전화 모양일 뿐)
    매치 뒤에 하이픈으로 숫자가 더 이어지면("010-1234-5678-12") 그 모양이 아니다. 하이픈 번호 한 덩어리라 계좌 쪽 규칙으로 본다"""
    for typ, pattern in (("PHONE", PHONE), ("RRN", RRN)):
        for x in pattern.finditer(norm, max(0, m.start() - 20), m.end() + 20):
            head = norm[m.start():x.start()]
            if (x.start() <= m.start() < x.end() or re.fullmatch(r"\d{1,2} ", head)
                    or (m.end() < x.end() and re.fullmatch(r"\d+ ", head))):
                if m.end() > x.end() and norm[x.end()] == "-":
                    continue
                return typ
    return None


def _is_account(norm, m):
    """계좌 후보(숫자 10자리 이상)가 계좌인지 앞뒤 창의 단어로 정한다
    창: 번호 앞 20자(라벨 + 예금주 이름이 들어갈 만큼), 뒤 10자("(국민은행)" 정도).
        단 앞뒤에 다른 번호가 있으면 그 번호까지만 본다(그 번호의 라벨이니까)
    순서: 전화 모양(_shape)이면 바로 앞에 계좌·통장 라벨이 있을 때만 계좌, 주민번호 모양이면 그 라벨(조사·괄호 허용)이
          바로 앞에 있거나 (주민번호 라벨이 바로 앞에 없고) 바로 앞뒤에 은행 이름이나 바로 뒤에 계좌·통장이 있을 때만 계좌(아니면 주민번호·전화 패턴에 넘긴다. 명세 7절은 type이 같아야 맞음이라,
          근처 단어만 보고 계좌로 바꾸면 가려져도 오답이 된다). 이 경우는 윗줄 규칙도 안 본다("계좌번호는 아래에\n010-1234-5678"은 전화)
          -> 바로 앞에 다른 번호 라벨이 붙어 있으면 계좌 아님
          -> 앞 창에 계좌 쪽 단어가 하나라도 있으면 계좌
          -> 줄 맨 앞이면 윗줄의 계좌·통장 -> 바로 뒤에 다른 번호 라벨이면 계좌 아님 -> 뒤 창에 계좌 쪽 단어가 있으면 계좌
    단어끼리 거리를 비교하지 않는다. 한국어는 어순이 자유로워서 거리 비교는 "폰으로 연락 주시고 110-...로 입금"을 놓친다
    예: "주민번호 900101-1234567 계좌 110-..." -> 앞 번호는 '주민번호' 라벨이 바로 앞에 있어 주민번호(뒤의 '계좌'는 다음 번호의 라벨),
        뒤 번호는 창이 잘려 '계좌'만 보여 계좌
        "연락처 010-1234-5678 / 110-123-456789 (신한)" -> 계좌의 앞 창은 " / "뿐이라 뒤의 '(신한)'을 본다
    한계: 근처에 계좌 쪽 단어만 있으면 라벨 없는 다른 번호도 계좌로 가린다(더 가리는 쪽).
          주민번호 모양 13자리 계좌는 바로 앞뒤에 계좌·통장·은행 이름이 없으면 RRN으로 분류된다(가려지긴 한다).
          ("1002123456789로 입금", "예금주 홍길동 1002123456789", "계좌번호 알려드릴게요 1002123456789",
           "환불 계좌 재확인 요청함\n1002123456789"처럼 윗줄에 계좌가 있는 경우도. 우리 1002…·농협 301…의 일부가 해당)
          반대로 라벨 없는 주민번호 바로 뒤에 은행 이름이 오면 계좌로 본다("홍길동 900101-1234567 국민은행 123456-…"의
          국민은행은 다음 계좌의 은행인데 끌어온다).
          주민번호·전화 뒤에 "-숫자"가 붙으면("900101-1234567-1") 하이픈 번호 한 덩어리로 보고 계좌 쪽 규칙을 따른다.
          "900101-1234567 우리 집"처럼 주민번호 바로 뒤에 은행 줄임말과 같은 말이 오면 계좌로 본다.
          전화번호 모양 평생계좌("계좌는 010-1234-5678")는 바로 앞이 "계좌"·"통장"(조사 없이)일 때만 계좌다.
          "계좌 두 개: 110-..., 1002-..."처럼 목록으로 이어지면 두 번째부터는 라벨이 창 밖이라 놓친다"""
    before = OTHER_NUMBER.split(norm[max(0, m.start() - 20):m.start()])[-1]
    after = OTHER_NUMBER.split(norm[m.end():m.end() + 10])[0]
    shape = _shape(norm, m)
    if shape == "PHONE":
        return bool(SHAPED_ACCOUNT_LABEL.search(before))
    if shape == "RRN":
        if RRN_SHAPED_ACCOUNT_LABEL.search(before):
            return True
        return not RRN_LABEL_BEFORE.search(before) and any(r.search(s) for r, s in (
            (BANK_BEFORE, before), (BANK_SHORT_BEFORE, before), (BANK_AFTER, after), (BANK_SHORT_AFTER, after),
            (RRN_SHAPED_ACCOUNT_AFTER, after)))
    if LABEL_BEFORE.search(before):
        return False
    if BANK_SHORT_BEFORE.search(before) or ACCOUNT_WORDS.search(before):
        return True
    # 번호가 줄 맨 앞이면 윗줄에 "계좌"·"통장"이 있는지 본다("계좌번호는 아래에 적어 주세요\n110-...").
    # 윗줄은 길어서 다른 단어(입금·은행 등)까지 보면 엉뚱한 번호를 계좌로 잡는다
    line = norm.rfind("\n", 0, m.start())
    if line >= 0 and not norm[line + 1:m.start()].strip():
        if re.search("계좌|통장", norm[norm.rfind("\n", 0, line) + 1:line]):
            return True
    if LABEL_AFTER.search(after):
        return False
    return bool(BANK_SHORT_AFTER.search(after) or ACCOUNT_WORDS.search(after))


# 앞에 있을수록 우선. 세 번째 칸은 추가 조건(없으면 None)
# 이메일이 맨 앞인 건 "01012345678@example.com"을 전화로 잘라 내지 않으려고
# 계좌가 주민번호·전화보다 앞인 건 "입금 계좌 1002123456789"(날짜처럼 생긴 계좌)·"입금 계좌 010-1234-5678"(평생계좌)을
# 주민번호·전화로 잘못 붙이지 않으려고. 계좌 조건이 안 맞으면 그 숫자는 뒤의 주민번호·전화 패턴이 다시 본다
PATTERNS = [("EMAIL", EMAIL, None), ("ACCOUNT", ACCOUNT, _is_account), ("RRN", RRN, None), ("PHONE", PHONE, None)]


def detect(text: str) -> list[dict]:
    norm = text.translate(_NORMALIZE)
    found = []
    for typ, pattern, condition in PATTERNS:
        for m in pattern.finditer(norm):
            if condition and not condition(norm, m):
                continue
            spans = [(typ, m.start(), m.end())]
            if typ == "EMAIL":
                # "010-1234-5678kim@example.com"처럼 이메일 앞에 붙여 쓴 전화번호는 떼어 낸다.
                # 구분자가 있는 전화만 뗀다("01012345678@example.com"은 그 자체가 메일 주소)
                p = PHONE.match(norm, m.start())
                if p and not p.group().isdigit() and norm[p.end()].isalpha():
                    spans = [("PHONE", m.start(), p.end()), ("EMAIL", p.end(), m.end())]
            for t, s, e in spans:
                _add(found, t, s, e)
    return sorted(found, key=lambda f: f["start"])


def _add(found, typ, s, e):
    hits = [f for f in found if s < f["end"] and f["start"] < e]
    if not hits:
        found.append({"type": typ, "start": s, "end": e, "source": "regex"})
        return
    # 이미 잡힌 구간과 겹치면 버리지 않고 합친다. 버리면 안 겹친 부분이 그대로 노출된다
    # 종류는 먼저 잡힌 쪽(우선순위가 높은 쪽)을 남긴다
    # (명세 마스킹 규칙 1 "겹친 부분만 잘라냄"은 정규식과 NER 사이 규칙이다. 정규식끼리는 합친다)
    keep = hits[0]
    keep["start"] = min([s] + [h["start"] for h in hits])
    keep["end"] = max([e] + [h["end"] for h in hits])
    for h in hits[1:]:
        found.remove(h)
