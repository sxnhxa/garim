@pytest.mark.parametrize("text", [
    "서울 강남구 테헤란로 123 (010-1234-5678)",
    "서울시 강남구 테헤란로 123 (연락처 010-1234-5678)",
    "서울 강남구 테헤란로 123 101동 202호(010-1234-5678)",
])
def test_cut_at_number(text):
    # 괄호 꼬리가 전화번호까지 먹어도 주소를 버리지 않고 번호 앞에서 자른다(버리면 주소가 노출된다)
    nums = detect(text)
    addr = detect_address(text, nums)
    assert addr and text.startswith("서울", addr[0]["start"])
    assert "테헤란로 123" in text[addr[0]["start"]:addr[0]["end"]]
    assert not any(a["start"] < n["end"] and n["start"] < a["end"] for a in addr for n in nums)


def test_detail_after_number_kept():
    # 번호 뒤에 이어지는 동·호도 주소로 남긴다(번호 앞에서만 자르면 "101동 202호"가 노출된다)
    text = "서울 강남구 테헤란로 123 (010-1234-5678) 101동 202호"
    nums = detect(text)
    got = [text[a["start"]:a["end"]] for a in detect_address(text, nums)]
    assert got == ["서울 강남구 테헤란로 123", "101동 202호"]
    # 괄호 안에서 번호보다 앞에 있는 동·호도 남긴다
    text = "테헤란로 123 (101동 202호, 010-1234-5678)"
    got = [text[a["start"]:a["end"]] for a in detect_address(text, detect(text))]
    assert got == ["테헤란로 123 (101동 202호"]


def test_no_slow_input():
    # 띄어쓰기 없는 긴 글에서 시·군·구 나누기가 폭발하지 않는다(요청 한 건이 서버를 붙잡지 않게)
    for unit in ["시", "구", "서울시강남구", "서울특별시 " * 8 + "1", "시" * 59 + "1", "구" * 61 + "1"]:
        text = (unit * (5000 // len(unit) + 1))[:5000]
        t0 = time.perf_counter()
        detect_address(text, detect(text))
        assert time.perf_counter() - t0 < 1.0, unit[:6]
