def found(text):
    return [text[e["start"]:e["end"]] for e in detect_address(text, detect(text))]


CONTEXTS = ["고객님 주소는 {a}입니다.", "주소는 {a}.", "{a}로 보내주세요", "배송지: {a}, 연락처 {p}", "{a}...",
            "홍길동,{a},{p}", "\"{a}\"", "({a})", "주소\n{a}\n끝", "{a} 앞에 두세요"]


def test_faker_addresses_covered():
    # 명세 7절: 정답을 빠짐없이 덮으면 맞음(넓어도 맞음)
    for i in range(1000):
        a = [fake.address, fake.road_address, fake.land_address, lambda: f"{fake.road_address()} {fake.address_detail()}"][i % 4]()
        text = CONTEXTS[i % len(CONTEXTS)].format(a=a, p=fake.phone_number())
        assert any(a in g for g in found(text)), text


