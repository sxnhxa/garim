# 은행별 계좌 자릿수 모양(국민·신한·우리·하나·농협·카카오뱅크·토스뱅크·붙여 쓴 13자리)
# 첫 자리 %는 1~9. 0으로 시작하면 0505-... 같은 전화번호 모양이 우연히 나와서 뺐다
ACCOUNT_FORMATS = [
    "%#####-##-######",
    "%##-###-######",
    "%###-###-######",
    "%##-######-#####",
    "%##-####-####-##",
    "%###-##-#######",
    "%###-####-####",
    "%############",
]


def test_accounts_found():
    # 계좌 단어가 번호 앞에 있을 때, 은행 이름이 뒤에 붙을 때, 정식 은행명일 때
    for _ in range(100):
        for fmt in ACCOUNT_FORMATS:
            value = fake.numerify(fmt)
            for text in [f"입금 계좌 {value}로 보내 주세요", f"{value} (국민) 홍길동", f"신한은행 {value}"]:
                assert spans(text) == [("ACCOUNT", value)], text


def test_accounts_in_everyday_sentences():
    # 은행 이름이 번호 뒤에 오거나, 앞에 택배비·전화·금액·날짜 같은 말이 끼어도 계좌 숫자가 한 글자도 노출되면 안 된다
    # (붙여 쓴 13자리가 주민번호 모양으로 나오면 RRN으로 가는 게 맞아서 종류는 안 보고 가려졌는지만 본다)
    templates = [
        "{a} 카카오로 보내 주세요",
        "택배비는 {a} 신한으로 보내 주세요",
        "휴대폰으로 연락 주시고 {a} 신한은행으로 입금해 주세요",
        "휴대폰으로 연락 주시고 {a}로 입금해 주세요",
        "환불 계좌는 주문번호 확인 후 {a}",
        "우체국 택배비는 {a}로 보내 주세요",
        "{a} 카카오요",
        "송금액 25000원 {a}",
        "입금 기한 2026.11.30 {a}",
        "기업 {a} 홍길동",
    ]
    for _ in range(50):
        for fmt in ACCOUNT_FORMATS:
            value = fake.numerify(fmt)
            for template in templates:
                text = template.format(a=value)
                start = text.index(value)
                covered = set()
                for e in detect(text):
                    covered.update(range(e["start"], e["end"]))
                assert set(range(start, start + len(value))) <= covered, text


